fn emit_enum(out: &mut String, name: &str, variants: &[&str]) {
    out.push_str("export type ");
    out.push_str(name);
    out.push_str(" = ");
    for (i, v) in variants.iter().enumerate() {
        if i > 0 {
            out.push_str(" | ");
        }
        out.push('"');
        out.push_str(v);
        out.push('"');
    }
    out.push_str(";\n\n");
}

fn emit_interface(out: &mut String, name: &str, fields: &[(&str, &str)]) {
    out.push_str("export interface ");
    out.push_str(name);
    out.push_str(" {\n");
    for (name, ts_type) in fields {
        if let Some(stripped) = name.strip_suffix('?') {
            out.push_str("  ");
            out.push_str(stripped);
            out.push_str("?: ");
        } else {
            out.push_str("  ");
            out.push_str(name);
            out.push_str(": ");
        }
        out.push_str(ts_type);
        out.push_str(";\n");
    }
    out.push_str("}\n\n");
}

