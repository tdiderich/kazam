fn generate_schema() -> String {
    // The schema file IS the source of truth - just re-emit it as canonical JSON.
    let schema = load_schema();

    let mut out = String::with_capacity(16384);
    out.push_str("{\n");

    // Enums
    let enums: Vec<(&String, &Vec<String>)> = schema.enums.iter().collect();
    out.push_str("  \"enums\": {\n");
    for (i, (name, variants)) in enums.iter().enumerate() {
        out.push_str("    \"");
        out.push_str(name);
        out.push_str("\": [");
        for (j, v) in variants.iter().enumerate() {
            if j > 0 {
                out.push_str(", ");
            }
            out.push('"');
            out.push_str(v);
            out.push('"');
        }
        out.push(']');
        if i < enums.len() - 1 {
            out.push(',');
        }
        out.push('\n');
    }
    out.push_str("  },\n");

    // Types
    let types: Vec<(&String, &OMap<SchemaField>)> = schema.types.iter().collect();
    out.push_str("  \"types\": {\n");
    for (i, (name, fields)) in types.iter().enumerate() {
        out.push_str("    \"");
        out.push_str(name);
        out.push_str("\": {\n");
        let field_list: Vec<(&String, &SchemaField)> = fields.iter().collect();
        for (j, (fname, field)) in field_list.iter().enumerate() {
            out.push_str("      \"");
            out.push_str(fname);
            out.push_str("\": { \"type\": \"");
            out.push_str(&field.field_type);
            out.push_str("\", \"required\": ");
            out.push_str(if field.required { "true" } else { "false" });
            out.push_str(", \"kind\": \"");
            out.push_str(&kind_of(fname, field, &schema));
            out.push_str("\" }");
            if j < field_list.len() - 1 {
                out.push(',');
            }
            out.push('\n');
        }
        out.push_str("    }");
        if i < types.len() - 1 {
            out.push(',');
        }
        out.push('\n');
    }
    out.push_str("  },\n");

    // Components
    let components_map: Vec<(&String, &OMap<SchemaField>)> = schema.components.iter().collect();
    out.push_str("  \"components\": {\n");
    for (i, (tag, fields)) in components_map.iter().enumerate() {
        out.push_str("    \"");
        out.push_str(tag);
        out.push_str("\": {\n");
        let field_list: Vec<(&String, &SchemaField)> = fields.iter().collect();
        for (j, (fname, field)) in field_list.iter().enumerate() {
            out.push_str("      \"");
            out.push_str(fname);
            out.push_str("\": { \"type\": \"");
            out.push_str(&field.field_type);
            out.push_str("\", \"required\": ");
            out.push_str(if field.required { "true" } else { "false" });
            out.push_str(", \"kind\": \"");
            out.push_str(&kind_of(fname, field, &schema));
            out.push_str("\" }");
            if j < field_list.len() - 1 {
                out.push(',');
            }
            out.push('\n');
        }
        out.push_str("    }");
        if i < components_map.len() - 1 {
            out.push(',');
        }
        out.push('\n');
    }
    out.push_str("  }\n");

    out.push_str("}\n");
    out
}

